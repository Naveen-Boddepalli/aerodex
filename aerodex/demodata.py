ROUTE_COLORS = [
    "#2456E8", "#F04438", "#12B76A", "#F59E0B", "#8B5CF6",
    "#EC4899", "#06B6D4", "#84CC16", "#F97316", "#6366F1",
]


def _short_date(period: str) -> str:
    try:
        return date.fromisoformat(period).strftime("%b %d")
    except ValueError:
        return period
