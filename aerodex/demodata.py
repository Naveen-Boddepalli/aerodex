"""Read-only view over ``demo/`` — the dataset the API serves when there is no
database.

``demo/`` is a frozen, deterministic run of the real pipeline against the
fixture adapter: 30 daily periods x 60 routes x 7 horizons, 75,552 rows, with
the index, the hashes and the publisher's artifacts alongside it. See
``demo/README.md``.

**Everything here is synthetic.** The fares came from a fixture adapter that
makes no network calls. This module exists so the dashboard has a real series
to draw, not so a fixture fare can be passed off as a measurement — every
response built from it carries ``data_source: "demo-synthetic"``, and the
dashboard renders that as a banner.

Loading is lazy and cached: the panel is parsed once on first request and the
per-route aggregates are computed once on top of it. A missing ``demo/``
directory is not an error — :func:`available` returns False and the API says
so, rather than the process failing to boot.
"""

from __future__ import annotations

import json
import logging
from datetime import date, timedelta
from functools import lru_cache
from pathlib import Path
from typing import Any

import pandas as pd

from aerodex.airports import carrier_name, city

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parent.parent
DEMO_DIR = ROOT / "demo"
CONFIG_DIR = ROOT / "config"

DATA_SOURCE = "demo-synthetic"

SYNTHETIC_NOTICE = (
    "Fixture-derived demo data. Every fare in this response was generated by "
    "the fixture adapter, not collected from a live source. Not a measurement."
)


def available() -> bool:
    """True when the demo dataset is present on disk."""
    return (DEMO_DIR / "panel.csv.gz").exists() and (DEMO_DIR / "index.csv").exists()


# ---------------------------------------------------------------------------
# Raw loaders (cached)
# ---------------------------------------------------------------------------


@lru_cache(maxsize=1)
def panel() -> pd.DataFrame:
    """The full demo panel, one row per collected itinerary quote."""
    df = pd.read_csv(DEMO_DIR / "panel.csv.gz")
    df["fare_inr"] = df["fare_inr_paise"] / 100.0
    df["route"] = df["origin"] + "-" + df["destination"]
    return df


@lru_cache(maxsize=1)
def index_series() -> pd.DataFrame:
    """The computed index, one row per daily period."""
    df = pd.read_csv(DEMO_DIR / "index.csv")
    df["period"] = df["period"].astype(str)
    return df


@lru_cache(maxsize=1)
def manifest() -> dict:
    path = DEMO_DIR / "MANIFEST.json"
    return json.loads(path.read_text()) if path.exists() else {}


@lru_cache(maxsize=1)
def artifact(name: str = "index_latest.json") -> dict:
    path = DEMO_DIR / "artifacts" / name
    return json.loads(path.read_text()) if path.exists() else {}


@lru_cache(maxsize=1)
def panel_config() -> dict:
    import yaml

    path = CONFIG_DIR / "panel.yaml"
    if not path.exists():
        return {}
    with path.open() as f:
        return yaml.safe_load(f)


@lru_cache(maxsize=1)
def methodology_config() -> dict:
    import yaml

    path = CONFIG_DIR / "methodology.yaml"
    if not path.exists():
        return {}
    with path.open() as f:
        return yaml.safe_load(f)


@lru_cache(maxsize=1)
def route_weights() -> dict[str, float]:
    """DGCA-derived panel weight per ``ORIGIN-DEST`` key."""
    return {
        f"{r['origin']}-{r['destination']}": float(r.get("weight") or 0.0)
        for r in panel_config().get("routes", [])
    }


# ---------------------------------------------------------------------------
# Derived aggregates (cached)
# ---------------------------------------------------------------------------


@lru_cache(maxsize=1)
def periods() -> list[str]:
    """Every collection period in the panel, ascending."""
    return sorted(panel()["period"].unique().tolist())


@lru_cache(maxsize=1)
def route_daily() -> pd.DataFrame:
    """Per route per period: best fare, median fare and quote count.

    ``best_fare`` is the cheapest all-inclusive economy quote across all seven
    booking horizons — what a traveller would see. ``median_fare`` is the more
    stable number and is what the route cards headline, because the minimum of
    420 quotes jumps around on noise alone.
    """
    df = panel()
    g = df.groupby(["route", "period"], as_index=False).agg(
        best_fare=("fare_inr", "min"),
        median_fare=("fare_inr", "median"),
        mean_fare=("fare_inr", "mean"),
        n_quotes=("fare_inr", "size"),
    )
    return g.sort_values(["route", "period"]).reset_index(drop=True)


@lru_cache(maxsize=1)
def route_cheapest_itinerary() -> dict[str, dict]:
    """The cheapest itinerary per route in the latest period.

    Gives each route card a real carrier, stop count and departure bucket
    instead of a random draw.
    """
    df = panel()
    latest = df[df["period"] == periods()[-1]]
    out: dict[str, dict] = {}
    for route, grp in latest.groupby("route"):
        row = grp.loc[grp["fare_inr"].idxmin()]
        out[str(route)] = {
            "carrier": str(row["carrier"]),
            "cabin": str(row.get("cabin", "economy")).capitalize(),
            "airline": carrier_name(str(row["carrier"])),
            "stops": int(row["stops"]),
            "duration_minutes": int(row["duration_minutes"]),
            "departure_time_bucket": str(row["departure_time_bucket"]),
            "horizon_days": int(row["horizon_days"]),
            "fare_inr": float(row["fare_inr"]),
        }
    return out


def _stops_label(n: int) -> str:
    return "Direct" if n == 0 else f"{n} Stop" if n == 1 else f"{n} Stops"


def _change_class(current: float, previous: float) -> str:
    if previous <= 0:
        return "stable"
    if current < previous * 0.99:
        return "drop"
    if current > previous * 1.01:
        return "rise"
    return "stable"


